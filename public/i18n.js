// Palabra de enlace entre día y mes ("26 de sep" / "26 sep"): "de" en es/ca/oc, nada en en/fr.
I18N.es.date_join = ' de '; I18N.ca.date_join = ' de '; I18N.oc.date_join = ' de ';
I18N.en.date_join = ' '; I18N.fr.date_join = ' ';

function daysShort() { return I18N[currentLang].days_short; }
function daysLong() { return I18N[currentLang].days_long; }
function monthsShort() { return I18N[currentLang].months_short; }
function monthsLong() { return I18N[currentLang].months_long; }

let currentLang = 'es';
function setLang(lang) { currentLang = I18N[lang] ? lang : 'es'; try { localStorage.setItem('tc_lang', currentLang); } catch {} }
function t(key) { return (I18N[currentLang] && I18N[currentLang][key]) ?? (I18N.es[key] ?? key); }
// Arranca con lo último conocido (localStorage) para evitar parpadeo de idioma antes de tener
// los ajustes del servidor; boot() en app.js lo corrige con el idioma real guardado en la cuenta.
try { const saved = localStorage.getItem('tc_lang'); if (saved && I18N[saved]) currentLang = saved; } catch {}

// Traduce el HTML estático (login/registro/onboarding shell) que no pasa por innerHTML dinámico.
function applyStaticI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
}
