let currentLang = 'es';
function setLang(lang) { currentLang = I18N[lang] ? lang : 'es'; try { localStorage.setItem('tc_lang', currentLang); } catch {} }
function t(key) { return (I18N[currentLang] && I18N[currentLang][key]) ?? (I18N.es[key] ?? key); }
// Arranca con lo último conocido (localStorage) para evitar parpadeo de idioma antes de tener
